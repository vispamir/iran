'use client';
import { useEffect, useRef, useState, type CSSProperties, type ReactNode } from 'react';
import type { Chart as ChartInstance, ChartConfiguration, ChartConfigurationCustomTypesPerDataset, ChartType, DefaultDataPoint } from 'chart.js';
import { readVisualTheme, useVisualTheme } from './useVisualTheme';
import './visualizations.css';

export interface ChartProps<TType extends ChartType = ChartType, TData = DefaultDataPoint<TType>, TLabel = unknown> {
  config: ChartConfiguration<TType, TData, TLabel> | ChartConfigurationCustomTypesPerDataset<TType, TData, TLabel>;
  title?: string;
  description?: string;
  className?: string;
  height?: CSSProperties['height'];
  /** Accessible canvas fallback, ideally a table of the underlying data. */
  children?: ReactNode;
  setup?: (api: typeof import('chart.js')) => void | Promise<void>;
  onReady?: (chart: ChartInstance<TType, TData, TLabel>) => void;
  onError?: (error: Error) => void;
}

export function Chart<TType extends ChartType = ChartType, TData = DefaultDataPoint<TType>, TLabel = unknown>({ config, title, description, className = '', height = 320, children, setup, onReady, onError }: ChartProps<TType, TData, TLabel>) {
  const canvas = useRef<HTMLCanvasElement>(null);
  const theme = useVisualTheme();
  const [status, setStatus] = useState<{ error?: string; busy: boolean }>({ busy: true });
  useEffect(() => {
    let cancelled = false;
    let chart: ChartInstance<TType, TData, TLabel> | undefined;
    setStatus({ busy: true });
    async function render() {
      const api = await import('chart.js');
      const { merge } = await import('chart.js/helpers');
      api.Chart.register(...api.registerables);
      await setup?.(api);
      if (cancelled || !canvas.current) return;
      const colors = readVisualTheme(canvas.current);
      const radial = config.data.datasets.some(dataset => {
        const type = dataset.type ?? ('type' in config ? config.type : undefined);
        return type === 'radar' || type === 'polarArea';
      });
      const defaults = {
        responsive: true, maintainAspectRatio: false, color: colors.ink,
        font: { family: colors.font },
        animation: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? false : undefined,
        plugins: {
          legend: { labels: { color: colors.muted, font: { family: colors.font }, usePointStyle: true, padding: 20 } },
          tooltip: { backgroundColor: colors.ink, titleColor: colors.background, bodyColor: colors.background, padding: 12, cornerRadius: 4, rtl: getComputedStyle(canvas.current).direction === 'rtl' },
        },
      };
      const options = merge({}, [defaults, config.options ?? {}]) as NonNullable<typeof config.options>;
      // Theme each configured scale without assuming numeric, category or time axes.
      const scales = options.scales as Record<string, Record<string, unknown>> | undefined;
      if (scales) {
        for (const key of Object.keys(scales)) {
          scales[key] = merge<Record<string, unknown>>({}, [{ grid: { color: colors.line }, border: { color: colors.line }, ticks: { color: colors.muted }, title: { color: colors.ink }, ...(radial ? { angleLines: { color: colors.line }, pointLabels: { color: colors.muted } } : {}) }, scales[key]]);
        }
      }
      const themePlugin = {
        id: 'iran-theme',
        beforeLayout(instance: ChartInstance) {
          // Includes implicit default scales generated by Chart.js.
          for (const scale of Object.values(instance.scales)) {
            const supplied = (config.options?.scales as Record<string, { ticks?: { color?: unknown }; grid?: { color?: unknown }; border?: { color?: unknown } }> | undefined)?.[scale.id];
            const themed = scale.options as unknown as { ticks?: { color: string }; grid?: { color: string }; border?: { color: string } };
            if (themed.ticks && !supplied?.ticks?.color) themed.ticks.color = colors.muted;
            if (themed.grid && !supplied?.grid?.color) themed.grid.color = colors.line;
            if (themed.border && !supplied?.border?.color) themed.border.color = colors.line;
          }
        },
      };
      const datasets = config.data.datasets.map((dataset, index) => {
        const type = dataset.type ?? ('type' in config ? config.type : undefined);
        const segmented = type === 'pie' || type === 'doughnut' || type === 'polarArea';
        const color = colors.palette[index % colors.palette.length];
        return { ...dataset, borderColor: dataset.borderColor ?? (segmented ? colors.background : color), backgroundColor: dataset.backgroundColor ?? (segmented ? colors.palette : `${color}99`) };
      });
      chart = new api.Chart(canvas.current, { ...config, data: { ...config.data, datasets }, options, plugins: [themePlugin, ...(config.plugins ?? [])] } as ChartConfiguration<TType, TData, TLabel>);
      setStatus({ busy: false });
      onReady?.(chart);
    }
    render().catch((reason: unknown) => {
      if (cancelled) return;
      chart?.destroy();
      const error = reason instanceof Error ? reason : new Error(String(reason));
      setStatus({ busy: false, error: error.message });
      onError?.(error);
    });
    return () => { cancelled = true; chart?.destroy(); };
  }, [config, setup, onReady, onError, theme]);
  return <figure className={`ir-visual ${className}`}>
    {(title || description) && <figcaption>{title}{description && <span className="ir-visual-description">{description}</span>}</figcaption>}
    {status.busy && <div role="status" className="ir-visual-status">Loading chart…</div>}
    {status.error && <div role="alert" className="ir-visual-status ir-visual-error">{status.error}</div>}
    <div className="ir-visual-stage ir-chart-stage" style={{ height }} aria-busy={status.busy}>
      <canvas ref={canvas} role="img" aria-label={[title ?? 'Chart', description].filter(Boolean).join('. ')}>{children ?? 'Chart data visualization'}</canvas>
    </div>
  </figure>;
}
